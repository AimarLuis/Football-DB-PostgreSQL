"""Step 5 - Run the 10 queries with example parameters and write
output/queries_results.md (question, author, SQL, sample of the result).

    python run_queries.py

Q10 changes data (DELETE + INSERT), so it runs inside an explicit
transaction: BEGIN ... COMMIT. If anything fails, ROLLBACK leaves the
golden_boot table exactly as it was.
"""
import os
import time

import psycopg2

from config import HERE, connect
from queries import QUERIES

SAMPLE_ROWS = 8


def markdown_table(columns, rows):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in rows:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(lines)


conn = connect()
conn.autocommit = True          # transactions are written explicitly (BEGIN/COMMIT)
cur = conn.cursor()

# Q10, part 1: the INSERT inside a transaction.
try:
    cur.execute(QUERIES["Q10"]["dml"])
    cur.execute("SELECT COUNT(*) FROM golden_boot")
    print("Q10 transaction committed:", cur.fetchone()[0], "rows in golden_boot")
except psycopg2.Error as e:
    cur.execute("ROLLBACK")
    print("Q10 failed, ROLLBACK:", e)

out = ["# SQL queries: results with example parameters (generated by run_queries.py)\n"]
for qid, q in QUERIES.items():
    start = time.time()
    cur.execute(q["sql"], q["params"])
    rows = cur.fetchall()
    ms = (time.time() - start) * 1000
    columns = [d[0] for d in cur.description]
    print(f"{qid:4s} {len(rows):4d} rows  {ms:7.0f} ms  {q['title']}")
    out += [f"## {qid}. {q['title']}\n",
            f"- **Author:** {q['author']}",
            f"- **Question:** {q['question']}",
            f"- **SQL constructs:** {q['constructs']}",
            f"- **Example parameters:** `{q['params']}`  ({len(rows)} rows, {ms:.0f} ms)\n"]
    if "dml" in q:
        out += ["Part 1 - stored inside a transaction:\n", "```sql" + q["dml"] + "```\n",
                "Part 2 - read by the app:\n"]
    out += ["```sql" + q["sql"] + "```\n",
            f"Sample of the result (first {SAMPLE_ROWS} rows):\n",
            markdown_table(columns, rows[:SAMPLE_ROWS]), "",
            f"**Why it matters:** {q['why']}", ""]
conn.close()

os.makedirs(os.path.join(HERE, "output"), exist_ok=True)
with open(os.path.join(HERE, "output", "queries_results.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print("Written output/queries_results.md")
